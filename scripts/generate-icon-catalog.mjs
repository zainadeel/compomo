#!/usr/bin/env node
/**
 * Generate lazy icon-loader catalogs for ds-icon.
 *
 * Each entry is a static-analyzable dynamic import (`() => import('@ds-mo/icons/svg/Bell')`)
 * so consumer bundlers code-split one tiny chunk per icon instead of carrying the whole
 * catalog (~340 kB raw) in the initial bundle. Glyphs load on demand, cache in the shared
 * icon cache (see icon-cache.ts), and apps can pre-register critical icons with
 * `registerIcons` for synchronous first paint.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'src', 'wc', 'components', 'Icon');
const require = createRequire(import.meta.url);

const metaPath = require.resolve('@ds-mo/icons/meta.json');
const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));

function writeCatalog(filename, exportName, icons, importPrefix) {
  const entries = icons
    .map(i => `  ${i.name}: () => import('${importPrefix}/${i.name}').then(m => m.${i.name}),`)
    .join('\n');

  const content = `/** Auto-generated by scripts/generate-icon-catalog.mjs — do not edit. */

export const ${exportName}: Record<string, () => Promise<string>> = {
${entries}
};
`;

  const outputPath = path.join(OUT_DIR, filename);
  if (fs.existsSync(outputPath) && fs.readFileSync(outputPath, 'utf8') === content) return;
  fs.writeFileSync(outputPath, content);
}

/**
 * ds-icon routes a name to its catalog by membership, so a name that exists in
 * two categories has no single correct answer — whichever catalog is consulted
 * first would silently win and change what an existing `name` renders.
 *
 * IcoMo makes this structurally possible: system icons are unprefixed while
 * flag/map exports carry a category prefix, so a future `src/map/Pin.svg` would
 * build to `MapPin` and collide with the existing `MapPin` system icon.
 *
 * Fail the build instead of letting precedence decide. Resolving this needs a
 * human — an upstream rename, or an explicit disambiguation in ds-icon.
 */
function assertNamesAreUniqueAcrossCategories(icons) {
  const categoriesByName = new Map();
  for (const { name, category } of icons) {
    if (!categoriesByName.has(name)) categoriesByName.set(name, new Set());
    categoriesByName.get(name).add(category);
  }

  const collisions = [...categoriesByName]
    .filter(([, categories]) => categories.size > 1)
    .map(([name, categories]) => `  ${name} — ${[...categories].sort().join(' and ')}`);

  if (collisions.length > 0) {
    throw new Error(
      `@ds-mo/icons@${meta.version} ships ${collisions.length} name(s) in more than one category:\n` +
        `${collisions.join('\n')}\n` +
        'ds-icon resolves a catalog from the name alone, so these are ambiguous.'
    );
  }
}

assertNamesAreUniqueAcrossCategories(meta.icons);

const system = meta.icons.filter(i => i.category === 'system');
const flags = meta.icons.filter(i => i.category === 'flag');
const maps = meta.icons.filter(i => i.category === 'map');

writeCatalog('system-icon-catalog.ts', 'systemIconLoaders', system, '@ds-mo/icons/svg');
writeCatalog('flag-icon-catalog.ts', 'flagIconLoaders', flags, '@ds-mo/icons/svg/flags');
writeCatalog('map-icon-catalog.ts', 'mapIconLoaders', maps, '@ds-mo/icons/svg/map');

console.log(
  `  Verified lazy icon-loader catalogs (${system.length} system, ${flags.length} flag, ${maps.length} map) from @ds-mo/icons@${meta.version}`
);
